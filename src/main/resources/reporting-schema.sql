-- Apply this once to existing databases before deploying the report-generation backend.
-- Generated PDFs are stored on the backend's persistent filesystem; only metadata is stored here.
CREATE TABLE IF NOT EXISTS demo.generated_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_type VARCHAR(30) NOT NULL CHECK (report_type IN ('SALES', 'PURCHASE', 'PAYMENTS', 'OUTSTANDING', 'DELIVERIES')),
    from_date DATE NOT NULL,
    to_date DATE NOT NULL,
    report_format VARCHAR(10) NOT NULL CHECK (report_format = 'PDF'),
    filters JSONB NOT NULL DEFAULT '{}'::jsonb,
    status VARCHAR(20) NOT NULL DEFAULT 'QUEUED'
        CHECK (status IN ('QUEUED', 'PROCESSING', 'COMPLETED', 'FAILED')),
    requested_by INTEGER NOT NULL REFERENCES demo.user_account(id),
    file_path TEXT,
    file_name VARCHAR(255),
    error_message VARCHAR(1000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMP,
    completed_at TIMESTAMP,
    CONSTRAINT generated_report_date_range_chk CHECK (from_date <= to_date)
);

CREATE INDEX IF NOT EXISTS idx_generated_report_queue
    ON demo.generated_report (status, created_at)
    WHERE status = 'QUEUED';

CREATE INDEX IF NOT EXISTS idx_generated_report_owner_created
    ON demo.generated_report (requested_by, created_at DESC);
