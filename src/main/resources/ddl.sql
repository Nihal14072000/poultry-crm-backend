-- Authentication accounts are separate from employee business types.
CREATE TABLE demo.user_account (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(100) NOT NULL UNIQUE,
    password_hash varchar(100) NOT NULL,
    role varchar(20) NOT NULL CHECK (role IN ('ADMIN', 'EMPLOYEE')),
    employee_id integer UNIQUE REFERENCES demo.employee(id),
    enabled boolean NOT NULL DEFAULT true,
    CONSTRAINT user_account_role_employee_check CHECK (
        (role = 'ADMIN' AND employee_id IS NULL)
        OR (role = 'EMPLOYEE' AND employee_id IS NOT NULL)
    )
);

CREATE UNIQUE INDEX user_account_single_admin
    ON demo.user_account (role)
    WHERE role = 'ADMIN';


