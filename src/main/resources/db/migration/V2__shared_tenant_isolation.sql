CREATE TABLE IF NOT EXISTS demo.generated_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_type VARCHAR(30) NOT NULL,
    from_date DATE NOT NULL,
    to_date DATE NOT NULL,
    report_format VARCHAR(10) NOT NULL DEFAULT 'PDF',
    filters JSONB NOT NULL DEFAULT '{}'::jsonb,
    status VARCHAR(20) NOT NULL DEFAULT 'QUEUED',
    requested_by INTEGER NOT NULL REFERENCES demo.user_account(id),
    tenant_id VARCHAR(64) NOT NULL DEFAULT 'default',
    file_path TEXT,
    file_name VARCHAR(255),
    error_message VARCHAR(1000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMP,
    completed_at TIMESTAMP,
    CONSTRAINT generated_report_date_range_chk CHECK (from_date <= to_date)
);
ALTER TABLE demo.generated_report ADD COLUMN IF NOT EXISTS tenant_id VARCHAR(64) NOT NULL DEFAULT 'default';

CREATE TABLE IF NOT EXISTS demo.business_record (
    id UUID PRIMARY KEY,
    tenant_id VARCHAR(64) NOT NULL REFERENCES demo.tenant(id),
    resource VARCHAR(64) NOT NULL,
    record_data JSONB NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_business_record_tenant_resource_updated
    ON demo.business_record (tenant_id, resource, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_report_tenant_owner_created
    ON demo.generated_report (tenant_id, requested_by, created_at DESC);

