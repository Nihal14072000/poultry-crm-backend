-- Backfill role_id for existing ADMIN accounts.
UPDATE demo.user_account ua
SET role_id = r.id
FROM demo.role r
WHERE ua.role = 'ADMIN'
  AND ua.role_id IS NULL
  AND r.tenant_id = ua.tenant_id
  AND r.name = 'Organization Admin';

-- Backfill role_id for existing EMPLOYEE accounts based on employee.type.
UPDATE demo.user_account ua
SET role_id = r.id
FROM demo.employee e
JOIN demo.role r ON r.tenant_id = e.tenant_id
WHERE ua.role = 'EMPLOYEE'
  AND ua.role_id IS NULL
  AND ua.employee_id = e.id
  AND LOWER(r.name) = LOWER(TRIM(e.type));
