-- Tenant-specific roles & permissions table and user_account.role_id link.

CREATE TABLE IF NOT EXISTS demo.role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL DEFAULT 1,
    name VARCHAR(100) NOT NULL,
    resources JSONB NOT NULL DEFAULT '[]'::jsonb,
    actions JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_role_tenant_name UNIQUE (tenant_id, name)
);

CREATE INDEX IF NOT EXISTS idx_role_tenant ON demo.role (tenant_id);

ALTER TABLE demo.user_account
    ADD COLUMN IF NOT EXISTS role_id BIGINT NULL REFERENCES demo.role(id);

